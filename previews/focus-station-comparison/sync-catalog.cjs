const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const catalog = require('../../js/products-data.js');

const product = catalog.getProduct('focus-station-walnut');
const variants = product.catalogVariants.map(({ option, rrp, dimensions }) => {
  const sku = product.skus[option];
  if (!sku || sku.dimensions !== dimensions.join(' × ') + ' см' || sku.price !== rrp) {
    throw new Error(`Check the active catalog for ${product.id} / ${option}`);
  }
  return {
    option,
    sku: sku.sku,
    size: dimensions[0],
    listPrice: rrp,
    price: catalog.calcDiscountedUnitPrice(rrp)
  };
});
const snapshot = { id: product.id, title: product.title, variants };
const output = '/* Generated by sync-catalog.cjs from js/products-data.js. */\n'
  + `const FOCUS_COMPARISON_CATALOG = ${JSON.stringify(snapshot, null, 2)};\n`;
const destination = join(__dirname, 'catalog.js');
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) {
    throw new Error('The comparison catalog snapshot is stale. Run sync-catalog.cjs.');
  }
} else {
  writeFileSync(destination, output);
}
